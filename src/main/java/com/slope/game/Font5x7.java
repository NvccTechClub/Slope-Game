package com.slope.game;

/**
 * A 5x7 bitmap font, held as one bitmask per glyph row. The game needs words on screen
 * for menus and prompts, and a handful of hand-drawn glyphs is a far smaller dependency
 * than a font loader and an atlas.
 *
 * <p>Each glyph is seven rows; within a row the low five bits are the pixels, most
 * significant bit leftmost. Unknown characters fall back to a blank.
 */
final class Font5x7 {
    static final int GLYPH_WIDTH = 5;
    static final int GLYPH_HEIGHT = 7;

    /** One column of blank between glyphs, in unscaled pixels. */
    static final int ADVANCE = GLYPH_WIDTH + 1;

    private static final int[] BLANK = { 0, 0, 0, 0, 0, 0, 0 };

    private static final int[][] LETTERS = {
        { 0x0E, 0x11, 0x11, 0x1F, 0x11, 0x11, 0x11 }, // A
        { 0x1E, 0x11, 0x11, 0x1E, 0x11, 0x11, 0x1E }, // B
        { 0x0E, 0x11, 0x10, 0x10, 0x10, 0x11, 0x0E }, // C
        { 0x1E, 0x11, 0x11, 0x11, 0x11, 0x11, 0x1E }, // D
        { 0x1F, 0x10, 0x10, 0x1E, 0x10, 0x10, 0x1F }, // E
        { 0x1F, 0x10, 0x10, 0x1E, 0x10, 0x10, 0x10 }, // F
        { 0x0E, 0x11, 0x10, 0x13, 0x11, 0x11, 0x0E }, // G
        { 0x11, 0x11, 0x11, 0x1F, 0x11, 0x11, 0x11 }, // H
        { 0x0E, 0x04, 0x04, 0x04, 0x04, 0x04, 0x0E }, // I
        { 0x07, 0x02, 0x02, 0x02, 0x02, 0x12, 0x0C }, // J
        { 0x11, 0x12, 0x14, 0x18, 0x14, 0x12, 0x11 }, // K
        { 0x10, 0x10, 0x10, 0x10, 0x10, 0x10, 0x1F }, // L
        { 0x11, 0x1B, 0x15, 0x11, 0x11, 0x11, 0x11 }, // M
        { 0x11, 0x19, 0x15, 0x13, 0x11, 0x11, 0x11 }, // N
        { 0x0E, 0x11, 0x11, 0x11, 0x11, 0x11, 0x0E }, // O
        { 0x1E, 0x11, 0x11, 0x1E, 0x10, 0x10, 0x10 }, // P
        { 0x0E, 0x11, 0x11, 0x11, 0x15, 0x12, 0x0D }, // Q
        { 0x1E, 0x11, 0x11, 0x1E, 0x14, 0x12, 0x11 }, // R
        { 0x0F, 0x10, 0x10, 0x0E, 0x01, 0x01, 0x1E }, // S
        { 0x1F, 0x04, 0x04, 0x04, 0x04, 0x04, 0x04 }, // T
        { 0x11, 0x11, 0x11, 0x11, 0x11, 0x11, 0x0E }, // U
        { 0x11, 0x11, 0x11, 0x11, 0x11, 0x0A, 0x04 }, // V
        { 0x11, 0x11, 0x11, 0x15, 0x15, 0x1B, 0x11 }, // W
        { 0x11, 0x11, 0x0A, 0x04, 0x0A, 0x11, 0x11 }, // X
        { 0x11, 0x11, 0x0A, 0x04, 0x04, 0x04, 0x04 }, // Y
        { 0x1F, 0x01, 0x02, 0x04, 0x08, 0x10, 0x1F }, // Z
    };

    private static final int[][] DIGITS = {
        { 0x0E, 0x11, 0x13, 0x15, 0x19, 0x11, 0x0E }, // 0
        { 0x04, 0x0C, 0x04, 0x04, 0x04, 0x04, 0x0E }, // 1
        { 0x0E, 0x11, 0x01, 0x02, 0x04, 0x08, 0x1F }, // 2
        { 0x1F, 0x02, 0x04, 0x02, 0x01, 0x11, 0x0E }, // 3
        { 0x02, 0x06, 0x0A, 0x12, 0x1F, 0x02, 0x02 }, // 4
        { 0x1F, 0x10, 0x1E, 0x01, 0x01, 0x11, 0x0E }, // 5
        { 0x06, 0x08, 0x10, 0x1E, 0x11, 0x11, 0x0E }, // 6
        { 0x1F, 0x01, 0x02, 0x04, 0x08, 0x08, 0x08 }, // 7
        { 0x0E, 0x11, 0x11, 0x0E, 0x11, 0x11, 0x0E }, // 8
        { 0x0E, 0x11, 0x11, 0x0F, 0x01, 0x02, 0x0C }, // 9
    };

    private Font5x7() {}

    /** The seven row masks for a character. Never null. */
    static int[] glyph(char c) {
        if (c >= 'a' && c <= 'z') {
            c = (char) (c - 'a' + 'A');
        }

        if (c >= 'A' && c <= 'Z') {
            return LETTERS[c - 'A'];
        }

        if (c >= '0' && c <= '9') {
            return DIGITS[c - '0'];
        }

        switch (c) {
            case ' ': return BLANK;
            case '.': return new int[] { 0x00, 0x00, 0x00, 0x00, 0x00, 0x0C, 0x0C };
            case ',': return new int[] { 0x00, 0x00, 0x00, 0x00, 0x00, 0x04, 0x08 };
            case ':': return new int[] { 0x00, 0x04, 0x04, 0x00, 0x04, 0x04, 0x00 };
            case ';': return new int[] { 0x00, 0x04, 0x00, 0x00, 0x04, 0x04, 0x08 };
            case '!': return new int[] { 0x04, 0x04, 0x04, 0x04, 0x04, 0x00, 0x04 };
            case '?': return new int[] { 0x0E, 0x11, 0x01, 0x02, 0x04, 0x00, 0x04 };
            case '-': return new int[] { 0x00, 0x00, 0x00, 0x1F, 0x00, 0x00, 0x00 };
            case '+': return new int[] { 0x00, 0x04, 0x04, 0x1F, 0x04, 0x04, 0x00 };
            case '=': return new int[] { 0x00, 0x00, 0x1F, 0x00, 0x1F, 0x00, 0x00 };
            case '_': return new int[] { 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x1F };
            case '/': return new int[] { 0x01, 0x02, 0x02, 0x04, 0x08, 0x08, 0x10 };
            case '\\': return new int[] { 0x10, 0x08, 0x08, 0x04, 0x02, 0x02, 0x01 };
            case '\'': return new int[] { 0x04, 0x04, 0x00, 0x00, 0x00, 0x00, 0x00 };
            case '"': return new int[] { 0x0A, 0x0A, 0x00, 0x00, 0x00, 0x00, 0x00 };
            case '(': return new int[] { 0x02, 0x04, 0x08, 0x08, 0x08, 0x04, 0x02 };
            case ')': return new int[] { 0x08, 0x04, 0x02, 0x02, 0x02, 0x04, 0x08 };
            case '[': return new int[] { 0x0E, 0x08, 0x08, 0x08, 0x08, 0x08, 0x0E };
            case ']': return new int[] { 0x0E, 0x02, 0x02, 0x02, 0x02, 0x02, 0x0E };
            case '<': return new int[] { 0x02, 0x04, 0x08, 0x10, 0x08, 0x04, 0x02 };
            case '>': return new int[] { 0x08, 0x04, 0x02, 0x01, 0x02, 0x04, 0x08 };
            case '*': return new int[] { 0x00, 0x0A, 0x04, 0x1F, 0x04, 0x0A, 0x00 };
            case '#': return new int[] { 0x0A, 0x0A, 0x1F, 0x0A, 0x1F, 0x0A, 0x0A };
            case '%': return new int[] { 0x18, 0x19, 0x02, 0x04, 0x08, 0x13, 0x03 };
            case '@': return new int[] { 0x0E, 0x11, 0x01, 0x0D, 0x15, 0x15, 0x0E };
            case '&': return new int[] { 0x0C, 0x12, 0x12, 0x0C, 0x15, 0x12, 0x0D };
            default: return BLANK;
        }
    }

    /** Width in unscaled pixels of a string, excluding the trailing gap. */
    static int measure(String text) {
        if (text == null || text.isEmpty()) {
            return 0;
        }

        return (text.length() * ADVANCE) - 1;
    }
}
